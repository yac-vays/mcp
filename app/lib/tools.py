"""
The MCP tools. Thin wrappers: argument docs for the agent, the backend lookup,
the user's credential and error conversion; the logic is in `app/lib/entity.py`.
"""

import logging
from typing import Annotated, Any, Literal

from mcp.server.mcpserver import Context, MCPServer
from mcp.server.mcpserver.exceptions import ToolError
from mcp_types import ToolAnnotations
from pydantic import Field

from app import consts
from app.lib import auth
from app.lib import backends
from app.lib import entity
from app.lib.yac import Yac
from app.model.err import MCPGatewayError

logger = logging.getLogger(__name__)

Backend = Annotated[str, Field(description="Backend name (see list_types)")]
Type = Annotated[str, Field(description="Entity type name (see list_types)")]
Name = Annotated[str, Field(description="Entity name")]
NewName = Annotated[
    str | None,
    Field(
        description="Name of the new entity. Required if the type's name_generated is"
        ' "never", optional for "optional", must be omitted for "enforced".'
    ),
]
Yaml = Annotated[
    str,
    Field(
        description="The whole entity as YAML document. Keep comments and key order"
        " (changing them needs the `cln` permission)."
    ),
]
Secrets = Annotated[
    dict[str, str] | None,
    Field(
        description='Cleartexts for password fields, keyed by data location, e.g.'
        ' {"#/users/0/password": "..."}. Never put passwords into the YAML.'
    ),
]
Message = Annotated[
    str,
    Field(
        description="Why the change is made (commit message body; letters, digits,"
        ' spaces, line breaks and @ ( ) " . , _ / - only)'
    ),
]
Run = Annotated[
    list[str] | None, Field(description="Names of actions to run with the change (optional)")
]
EditToken = Annotated[
    str | None,
    Field(
        description="The `edit_token` from read_entity. Makes sure nobody changed the"
        " entity in the meantime (recommended)."
    ),
]

READ = ToolAnnotations(read_only_hint=True, open_world_hint=False)
WRITE = ToolAnnotations(read_only_hint=False, destructive_hint=False, open_world_hint=False)
EDIT = ToolAnnotations(
    read_only_hint=False, destructive_hint=True, idempotent_hint=True, open_world_hint=False
)
DESTRUCTIVE = ToolAnnotations(read_only_hint=False, destructive_hint=True, open_world_hint=False)

INSTRUCTIONS = """\
Access to YAC backends: Git repositories of YAML files ("entities") of several
types, with permissions per user. You act as the logged-in user.

Workflow: list_types -> list_entities -> read_entity (YAML, JSON schema,
field notes, edit_token). To change data, edit the YAML, check it with
validate until it is valid, then commit with create / edit. For small
changes, edit also takes a `data` patch instead of the whole YAML.

The JSON schema is generated for the current data and user (it can change
with the data). Missing fields with defaults are filled in automatically.
Read the field notes: some fields are generated by the server (leave them
empty or write "~generate"), passwords go into the `secrets` argument.
Never invent secrets or random values yourself.
"""


def _client(ctx: Context, backend: str) -> Yac:
    return Yac(backends.get(backend), auth.upstream_token(ctx))


async def _call(ctx: Context, backend: str, func, *args) -> dict:
    try:
        client = _client(ctx, backend)
        result = await func(client, *args)
    except MCPGatewayError as error:
        raise ToolError(str(error)) from error
    if client.warnings:
        result["warnings"] = client.warnings
    return result


def register(mcp: MCPServer) -> None:  # pylint: disable=too-many-locals
    @mcp.tool(annotations=READ)
    async def list_types(
        ctx: Context,
        backend: Annotated[str | None, Field(description="Only this backend")] = None,
    ) -> dict[str, Any]:
        """List the backends and their entity types (incl. actions and logs)."""
        names = [backend] if backend else [b.name for b in backends.config().backends]
        result: dict[str, Any] = {"backends": []}
        for name in names:
            try:
                typ = await _call(ctx, name, _types)
                result["backends"].append({**typ, "name": name, "title": backends.get(name).title})
            except ToolError as error:
                if backend:
                    raise
                result["backends"].append({"name": name, "error": str(error)})
        return result

    async def _types(client: Yac) -> dict:
        return {"types": await entity.list_types(client)}

    @mcp.tool(annotations=READ)
    async def list_entities(
        ctx: Context,
        backend: Backend,
        type: Type,  # pylint: disable=redefined-builtin
        search: Annotated[str, Field(description="Substring of the name")] = "",
        skip: Annotated[int, Field(ge=0)] = 0,
        limit: Annotated[int, Field(gt=0, le=1000)] = 100,
    ) -> dict[str, Any]:
        """List the entities of a type you may see (names, options, your permissions)."""
        return await _call(ctx, backend, entity.list_entities, type, search, skip, limit)

    @mcp.tool(annotations=READ)
    async def read_entity(ctx: Context, backend: Backend, type: Type, name: Name) -> dict[str, Any]:  # pylint: disable=redefined-builtin
        """
        Read an entity: its YAML, the JSON schema for editing it, field notes,
        your permissions, limit usages and an edit_token for edit.
        """
        return await _call(ctx, backend, entity.read_entity, type, name)

    @mcp.tool(annotations=READ)
    async def new_entity(ctx: Context, backend: Backend, type: Type) -> dict[str, Any]:  # pylint: disable=redefined-builtin
        """
        Start a new entity: a YAML document with the defaults, the JSON schema,
        field notes and the name rules. Edit it, validate it, then create it.
        """
        return await _call(ctx, backend, entity.new_entity, type)

    @mcp.tool(annotations=READ)
    async def validate(
        ctx: Context,
        backend: Backend,
        type: Type,  # pylint: disable=redefined-builtin
        operation: Literal["create", "edit"],
        yaml: Annotated[str | None, Field(description="The whole entity as YAML")] = None,
        data: Annotated[
            dict | None, Field(description="edit only: patch instead of the whole YAML")
        ] = None,
        name: Annotated[
            str | None,
            Field(
                description="Entity name: required for edit; for create unless the type"
                " generates names (see name_generated in list_types)"
            ),
        ] = None,
        edit_token: EditToken = None,
        secrets: Secrets = None,
    ) -> dict[str, Any]:
        """
        Check an entity without changing anything: all errors with their data
        locations, the values the server would generate and the applied defaults.
        """
        return await _call(
            ctx, backend, entity.validate, type, operation, name, yaml, data, edit_token, secrets
        )

    @mcp.tool(annotations=WRITE)
    async def create(
        ctx: Context,
        backend: Backend,
        type: Type,  # pylint: disable=redefined-builtin
        name: NewName,
        yaml: Yaml,
        message: Message = "",
        secrets: Secrets = None,
        run: Run = None,
    ) -> dict[str, Any]:
        """Create (commit) a new entity. Nothing is changed if it is not valid."""
        return await _call(
            ctx, backend, entity.create, type, name, yaml, secrets, message, run or []
        )

    @mcp.tool(annotations=EDIT)
    async def edit(
        ctx: Context,
        backend: Backend,
        type: Type,  # pylint: disable=redefined-builtin
        name: Name,
        yaml: Annotated[str | None, Field(description="The whole entity as YAML")] = None,
        data: Annotated[
            dict | None,
            Field(
                description="Instead of yaml: a patch; objects are merged, lists and values"
                ' replaced, "~undefined" removes a key'
            ),
        ] = None,
        edit_token: EditToken = None,
        message: Message = "",
        secrets: Secrets = None,
        run: Run = None,
    ) -> dict[str, Any]:
        """Edit (commit) an existing entity. Nothing is changed if it is not valid."""
        return await _call(
            ctx, backend, entity.edit, type, name, yaml, data, edit_token, secrets, message,
            run or [],
        )

    @mcp.tool(annotations=DESTRUCTIVE)
    async def delete(
        ctx: Context,
        backend: Backend,
        type: Type,  # pylint: disable=redefined-builtin
        name: Name,
        message: Message = "",
        run: Run = None,
    ) -> dict[str, Any]:
        """Delete an entity."""
        return await _call(ctx, backend, entity.delete, type, name, message, run or [])

    @mcp.tool(annotations=DESTRUCTIVE)
    async def run_action(
        ctx: Context,
        backend: Backend,
        type: Type,  # pylint: disable=redefined-builtin
        name: Name,
        action: Annotated[str, Field(description="Action name (see list_types)")],
    ) -> dict[str, Any]:
        """Run an action on an entity (see the action's description and `dangerous`)."""
        return await _call(ctx, backend, entity.run_action, type, name, action)

    @mcp.tool(annotations=READ)
    async def read_logs(  # pylint: disable=redefined-builtin
        ctx: Context,
        backend: Backend,
        type: Type,
        name: Name,
        log: Annotated[
            str | None,
            Field(
                description="Name of a log whose entries have `has_content`: returns its"
                " content document (e.g. a YAML file or a Markdown how-to) instead of"
                " the entries"
            ),
        ] = None,
    ) -> dict[str, Any]:
        """
        Read the logs of an entity (e.g. the progress of actions, problems, status
        documents), or the content document of one log.
        """
        return await _call(ctx, backend, entity.read_logs, type, name, log)

    if consts.ENV.read_only:
        for tool in ("create", "edit", "delete", "run_action"):
            mcp.remove_tool(tool)
