"""
Renderer plugin for VAYS' `random_string`: a plaintext random value (UUID,
token, machine ID, ...) that is generated once and then kept.

Mirrors `src/utils/randomString.ts` and `RandomStringRenderer.tsx` of VAYS.
"""

import uuid

from app.model.plg import Error, Keep, RendererContext, Set

ALPHANUMERIC = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789"
CHARSETS = {
    "alphanumeric": ALPHANUMERIC,
    "hex": "0123456789abcdef",
    "base64url": ALPHANUMERIC + "-_",
    "ascii_printable": ALPHANUMERIC + "!#$%&()*+,-./:;<=>?@[]^_{|}~",
}


def _generate(options: dict) -> str:
    fmt = options.get("format", "alphanumeric")
    length = int(options.get("length", 32))
    if fmt == "uuid":
        return str(uuid.uuid4())
    if fmt == "custom":
        charset = options.get("charset")
        if not charset or len(set(charset)) > 256:
            raise ValueError("format 'custom' requires a 'charset' of 1 to 256 distinct characters")
        return RendererContext.random(charset, length)
    if fmt not in CHARSETS:
        raise ValueError(f"unknown random string format '{fmt}'")
    return RendererContext.random(CHARSETS[fmt], length)


def describe(options: dict, schema: dict) -> str:
    if "default" in schema:
        return "Random value field; its schema default applies (nothing is generated)."
    fmt = options.get("format", "alphanumeric")
    size = "" if fmt == "uuid" else f", {int(options.get('length', 32))} characters"
    return (
        f"Generated by the server ({fmt}{size}) when left empty, then kept. Write"
        ' "~generate" to replace it with a new random value, or set a value explicitly.'
    )


def prepare(ctx: RendererContext):
    try:
        if ctx.generate_requested:
            value = _generate(ctx.options)
            return Set(value, {"generated": True, "value": value})
        if not ctx.agent_value_empty or ctx.has_default:
            return Keep()
        # Set once: an edit that dropped the field keeps the stored value.
        if ctx.operation == "edit" and ctx.has_current and not ctx.in_array:
            return Set(ctx.current, {"kept": "stored value"})
        value = _generate(ctx.options)
        return Set(value, {"generated": True, "value": value})
    except ValueError as error:
        return Error(f"cannot generate a value ({error}), check the field's renderer_options")


TEST_VECTORS = [
    (
        {"options": {"format": "hex", "length": 16}},
        lambda r: isinstance(r, Set)
        and len(r.value) == 16
        and set(r.value) <= set(CHARSETS["hex"]),
    ),
    (
        {"options": {"format": "uuid"}},
        lambda r: isinstance(r, Set) and str(uuid.UUID(r.value)) == r.value,
    ),
    (
        {"options": {"format": "custom", "charset": "ab", "length": 50}},
        lambda r: isinstance(r, Set) and set(r.value) <= {"a", "b"} and len(r.value) == 50,
    ),
    ({"options": {"format": "custom"}}, lambda r: isinstance(r, Error)),
    ({}, lambda r: isinstance(r, Set) and len(r.value) == 32 and r.value.isalnum()),
    ({"agent_value": "given"}, lambda r: isinstance(r, Keep)),
    ({"schema": {"default": "x"}}, lambda r: isinstance(r, Keep)),
    (
        {"agent_value": "~generate", "current": "old"},
        lambda r: isinstance(r, Set) and r.value != "old",
    ),
    ({"operation": "edit", "current": "old"}, lambda r: isinstance(r, Set) and r.value == "old"),
    (
        {"operation": "edit", "current": "old", "pattern": "#/l/*/id", "loc": "#/l/0/id"},
        lambda r: isinstance(r, Set) and r.value != "old",
    ),
]
