"""
Renderer plugin for VAYS' `age_secret`: a random secret that is generated by
the server and stored only as ASCII-armored AGE ciphertext.

Mirrors `src/utils/ageEncrypt.ts` and `AgeSecretRenderer.tsx` of VAYS. The
cleartext is only returned to the agent if `YAC_MCP_REVEAL_GENERATED_SECRETS`
is enabled (it would end up in the agent's transcript).
"""

import pyrage

from app.model.plg import Error, Keep, RendererContext, Set

ALPHANUMERIC = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789"
CHARSETS = {
    "alphanumeric": ALPHANUMERIC,
    "hex": "0123456789abcdef",
    "base64url": ALPHANUMERIC + "-_",
    "ascii_printable": ALPHANUMERIC + "!#$%&()*+,-./:;<=>?@[]^_{|}~",
}
ARMOR_HEADER = "-----BEGIN AGE ENCRYPTED FILE-----"


def encrypt(plaintext: str, recipient: str) -> str:
    key = pyrage.x25519.Recipient.from_str(recipient.strip())
    return pyrage.encrypt(plaintext.encode(), [key], armored=True).decode()


def describe(_options: dict, _schema: dict) -> str:
    return (
        "Secret generated by the server and stored encrypted (AGE). Leave it empty"
        ' (or keep the stored ciphertext); write "~generate" to replace it with a new'
        " secret. Never write a cleartext here."
    )


def _generate(ctx: RendererContext):
    recipient = ctx.options.get("age_public_key")
    if not recipient:
        return Error("the field has no `age_public_key` in its renderer_options")
    charset = ctx.options.get("charset", "alphanumeric")
    if charset not in CHARSETS:
        return Error(f"unknown charset '{charset}' in the field's renderer_options")
    secret = ctx.random(CHARSETS[charset], int(ctx.options.get("length", 32)))
    try:
        ciphertext = encrypt(secret, recipient)
    except pyrage.RecipientError as error:
        return Error(f"the configured age_public_key is not valid ({error})")
    report: dict = {"generated": True}
    if ctx.reveal_secrets:
        report["secret"] = secret
    else:
        report["note"] = (
            "The cleartext is not returned to agents. To get one, the user can"
            " regenerate the secret in VAYS."
        )
    return Set(ciphertext, report)


def prepare(ctx: RendererContext):
    if ctx.generate_requested:
        return _generate(ctx)
    if ctx.agent_value_empty:
        if ctx.operation == "edit" and ctx.has_current and not ctx.in_array:
            return Set(ctx.current, {"kept": "stored value"})
        return _generate(ctx)
    if ctx.is_stored_value:
        return Keep()
    return Error(
        "age_secret values are generated by the server: keep the stored ciphertext,"
        ' leave the field empty or write "~generate". Never write a cleartext here.'
    )


_KEY = pyrage.x25519.Identity.generate()
_RECIPIENT = str(_KEY.to_public())


def _decrypts(result, length: int, alphabet: str) -> bool:
    if not isinstance(result, Set) or not result.value.startswith(ARMOR_HEADER):
        return False
    secret = pyrage.decrypt(result.value.encode(), [_KEY]).decode()
    return len(secret) == length and set(secret) <= set(alphabet)


TEST_VECTORS = [
    (
        {"options": {"age_public_key": _RECIPIENT}},
        lambda r: _decrypts(r, 32, CHARSETS["alphanumeric"]) and "secret" not in r.report,
    ),
    (
        {"options": {"age_public_key": _RECIPIENT, "length": 12, "charset": "hex"}},
        lambda r: _decrypts(r, 12, CHARSETS["hex"]),
    ),
    (
        {"options": {"age_public_key": _RECIPIENT}, "reveal_secrets": True},
        lambda r: _decrypts(r, 32, ALPHANUMERIC) and len(r.report["secret"]) == 32,
    ),
    ({"options": {}}, lambda r: isinstance(r, Error)),
    ({"options": {"age_public_key": "age1invalid"}}, lambda r: isinstance(r, Error)),
    (
        {"options": {"age_public_key": _RECIPIENT}, "agent_value": "cleartext"},
        lambda r: isinstance(r, Error),
    ),
    (
        {
            "options": {"age_public_key": _RECIPIENT},
            "agent_value": "CT",
            "stored_values": ("CT",),
        },
        lambda r: isinstance(r, Keep),
    ),
    (
        {"options": {"age_public_key": _RECIPIENT}, "operation": "edit", "current": "CT"},
        lambda r: isinstance(r, Set) and r.value == "CT",
    ),
    (
        {"options": {"age_public_key": _RECIPIENT}, "agent_value": "~generate", "current": "CT"},
        lambda r: _decrypts(r, 32, ALPHANUMERIC),
    ),
]
